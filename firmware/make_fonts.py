#!/usr/bin/env python3
"""Turns the app's fonts into bitmap fonts for the sensor's screen (firmware/SpeedLidar/fonts.h).

Each glyph is stored as 4-bit coverage (16 levels of anti-aliasing), so the numbers on the 1.9" screen have
the same smooth edges as the Screen Lab preview.

    python3 firmware/make_fonts.py --fonts DIR     # DIR holds BarlowCondensed-ExtraBold.ttf,
                                                   # BarlowCondensed-Bold.ttf and Barlow-SemiBold.ttf
    python3 firmware/make_fonts.py --stand-in      # local preview only: DejaVu / Inter instead of Barlow

The "Screen fonts" GitHub workflow downloads Barlow (SIL Open Font License) and runs this for you.
"""
import argparse, os, sys
from PIL import ImageFont, Image, ImageDraw

ASCII = "".join(chr(c) for c in range(32, 127))
EXTRA = "\u00b7\u2013\u2019\u2026\u2212\u00b0"   # middle dot, en dash, right quote, ellipsis, minus, degree
FULL = ASCII + EXTRA
NUM = " 0123456789.'\"-%:−+°"
CAPS = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.'\"-%!?:·+°"

# (C name, face, size in px, characters). Sizes match the Screen Lab's Bold style.
FONTS = [
    ("F_XB72", "xb", 72, NUM),     # the big number (top speed, last 5 m, live speed)
    ("F_XB58", "xb", 58, CAPS),    # GO WHEN / READY, the distance on the ready screen
    ("F_XB34", "xb", 34, FULL),
    ("F_XB24", "xb", 24, FULL),
    ("F_XB18", "xb", 18, FULL),    # the result row
    ("F_XB15", "xb", 15, FULL),    # status strip
    ("F_B20",  "b",  20, FULL),    # units beside the big number
    ("F_B13",  "b",  13, FULL),
    ("F_B11",  "b",  11, FULL),    # small labels
    ("F_S13",  "s",  13, FULL),    # body text
    ("F_S11",  "s",  11, FULL),
]
FILES = {"xb": "BarlowCondensed-ExtraBold.ttf", "b": "BarlowCondensed-Bold.ttf", "s": "Barlow-SemiBold.ttf"}
STAND_IN = {"xb": "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf",
            "b": "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf",
            "s": "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf"}


def build(cname, path, size, chars):
    font = ImageFont.truetype(path, size)
    asc, desc = font.getmetrics()
    glyphs, bmp = [], bytearray()
    for ch in sorted(set(chars), key=ord):
        adv = font.getlength(ch)
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bmp)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            px = im.load()
            for y in range(h):
                row = 0
                for x in range(w):
                    v = (px[x, y] * 15 + 127) // 255
                    if x % 2 == 0: row = v << 4
                    else: bmp.append(row | v); row = 0
                if w % 2: bmp.append(row)
        glyphs.append((ord(ch), off, w, h, x0, y0, int(round(adv * 16))))
    out = [f"static const uint8_t {cname}_bmp[] PROGMEM = {{"]
    for i in range(0, len(bmp), 32):
        out.append("  " + ",".join(str(b) for b in bmp[i:i + 32]) + ",")
    if not bmp: out.append("  0")
    out.append("};")
    out.append(f"static const Glyph {cname}_g[] PROGMEM = {{")
    for g in glyphs: out.append("  {%d,%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"static const Font {cname} = {{{cname}_g, {len(glyphs)}, {cname}_bmp, {asc}, {desc}, {size}}};")
    return "\n".join(out), len(bmp)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts", help="folder with the Barlow .ttf files")
    ap.add_argument("--stand-in", action="store_true", help="use system fonts (local preview only)")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "SpeedLidar", "fonts.h"))
    a = ap.parse_args()
    if not a.fonts and not a.stand_in: sys.exit("give --fonts DIR or --stand-in")
    path = (lambda f: STAND_IN[f]) if a.stand_in else (lambda f: os.path.join(a.fonts, FILES[f]))
    parts, total = [], 0
    for cname, face, size, chars in FONTS:
        src, n = build(cname, path(face), size, chars); parts.append(src); total += n
    src = "\n".join([
        "// Generated by firmware/make_fonts.py" + (" with STAND-IN fonts (preview only)" if a.stand_in else " from Barlow (SIL Open Font License)") + ". Don't edit.",
        "#pragma once",
        "#include <stdint.h>",
        "#ifndef PROGMEM",
        "#define PROGMEM",
        "#endif",
        "// one character: 4-bit coverage, rows padded to whole bytes; x/y = offset of its top-left from the pen",
        "// position on the baseline; adv = advance in 1/16 px",
        "struct Glyph { uint32_t cp; uint32_t off; uint8_t w, h; int8_t x, y; uint16_t adv; };",
        "struct Font { const Glyph* g; uint16_t n; const uint8_t* bmp; uint8_t ascent, descent, size; };",
        *parts, ""])
    open(a.out, "w").write(src)
    print(f"{a.out}: {len(FONTS)} fonts, {total // 1024} KB of glyphs")


if __name__ == "__main__":
    main()
