"""Builds the phone app into one file.

    python3 src/build.py

Writes:
  index.html, manifest.webmanifest, sw.js   the app as GitHub Pages serves it (installable, works offline)
  firmware/SpeedLidar/page.h                the same app, wrapped so the ESP32 sketch can serve it
  firmware/SpeedLidar/assets.h              the home-screen icons and app manifest, served by the sensor too
"""
import base64, hashlib, os, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
read = lambda name: open(os.path.join(HERE, name), encoding="utf-8").read()
font = lambda name: base64.b64encode(open(os.path.join(HERE, "fonts", name), "rb").read()).decode()

# report font (Inter, SIL Open Font License), embedded because the sensor's Wi-Fi has no internet
FONTS = ('@font-face{font-family:"Report Sans";src:url(data:font/woff;base64,%s) format("woff");font-weight:100 550;font-style:normal}'
         '@font-face{font-family:"Report Sans";src:url(data:font/woff;base64,%s) format("woff");font-weight:551 900;font-style:normal}'
         ) % (font("Inter-Regular.woff"), font("Inter-SemiBold.woff"))

app = read("app.js").replace("/*__REPORT__*/", read("report.js"))
html = read("shell.html").replace("/*__FONTS__*/", FONTS).replace("/*__ENGINE__*/", read("engine.js")).replace("/*__APP__*/", app)
assert ")rawliteral" not in html, "page contains the raw-string terminator"

open(os.path.join(ROOT, "index.html"), "w", encoding="utf-8").write(html)
open(os.path.join(ROOT, "firmware", "SpeedLidar", "page.h"), "w", encoding="utf-8").write(
    "// Generated by src/build.py from the files in src/ - edit those, then rebuild.\n#pragma once\n"
    'const char PAGE_HTML[] PROGMEM = R"rawliteral(\n' + html + '\n)rawliteral";\n')

# installable app: manifest + offline cache (the version changes whenever the app or an icon changes)
ICONS = ["apple-touch-icon.png", "icon-192.png", "icon-512.png", "icon-maskable-512.png", "favicon-32.png"]
manifest = read("manifest.webmanifest")
open(os.path.join(ROOT, "manifest.webmanifest"), "w", encoding="utf-8").write(manifest)
h = hashlib.sha1(html.encode()); [h.update(open(os.path.join(ROOT, "icons", f), "rb").read()) for f in ICONS]
open(os.path.join(ROOT, "sw.js"), "w", encoding="utf-8").write(read("sw.js").replace("__VERSION__", h.hexdigest()[:10]))

# the sensor serves the same icons and manifest, so "Add to Home Screen" from 192.168.4.1 gets the real icon
def arr(name, data):
    body = ",".join(str(b) for b in data)
    return f"static const uint8_t {name}[] PROGMEM = {{{body}}};\nstatic const size_t {name}_LEN = {len(data)};\n"
parts = ["// Generated by src/build.py - home-screen icons and app manifest served by the sensor.\n#pragma once\n#include <Arduino.h>\n"]
parts.append(arr("ASSET_MANIFEST", manifest.encode()))
for f in ICONS:
    parts.append(arr("ASSET_" + f.replace("-", "_").replace(".png", "").upper(), open(os.path.join(ROOT, "icons", f), "rb").read()))
open(os.path.join(ROOT, "firmware", "SpeedLidar", "assets.h"), "w", encoding="utf-8").write("".join(parts))
print(f"index.html and page.h: {len(html):,} bytes · icons: {sum(os.path.getsize(os.path.join(ROOT, 'icons', f)) for f in ICONS):,} bytes")
